#!/usr/bin/env python3
"""Export consistent award canvases and standard portrait favicons.

Background extraction is performed by imagegen, not this script.
This script only fits finished assets onto equal canvases and exports icon sizes.
"""
from pathlib import Path
from PIL import Image, ImageOps
import json, shutil

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / 'website'
SIZE = (1200, 900)

def save_png(im, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.stem + '.exporting.png')
    im.save(temp, 'PNG', optimize=True)
    with Image.open(temp) as check:
        check.verify()
    temp.replace(path)

def main():
    edits = json.loads((ROOT/'content/award-image-edit-prompts.json').read_text())
    for edit in edits['edits']:
        # Retain the alpha generated by imagegen; remove only unused transparent margins.
        source = ROOT / edit['projectSource']
        with Image.open(source) as im:
            im = im.convert('RGBA')
            bounds = im.getchannel('A').getbbox()
            fitted = ImageOps.contain(im.crop(bounds), (1020, 780), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', SIZE)
        canvas.alpha_composite(fitted, ((SIZE[0]-fitted.width)//2, SIZE[1]-60-fitted.height))
        save_png(canvas, SITE / edit['output'])

    for original, output in [
        ('Innovatex-hackathon-bubt.png', 'innovatex-hackathon-card.png'),
        ('Research-week-runner up.png', 'research-week-card.png'),
    ]:
        with Image.open(SITE/'assets/conferences'/original) as im:
            fitted = ImageOps.contain(ImageOps.exif_transpose(im).convert('RGBA'), (1200, 900), Image.Resampling.LANCZOS)
        canvas = Image.new('RGBA', SIZE)
        canvas.alpha_composite(fitted, ((SIZE[0]-fitted.width)//2, (SIZE[1]-fitted.height)//2))
        save_png(canvas, SITE/'assets/awards/cards'/output)

    icon_dir = SITE/'assets/icons'
    icon_dir.mkdir(parents=True, exist_ok=True)
    with Image.open(icon_dir/'me.png') as im:
        icon = ImageOps.contain(im.convert('RGBA'), (512, 512), Image.Resampling.LANCZOS)
        master = Image.new('RGBA', (512, 512))
        master.alpha_composite(icon, ((512-icon.width)//2, (512-icon.height)//2))
        for size in [16, 32, 48, 180, 192, 512]:
            name = 'apple-touch-icon.png' if size == 180 else f'favicon-{size}.png'
            save_png(master.resize((size, size), Image.Resampling.LANCZOS), icon_dir/name)
        master.save(SITE/'favicon.ico', format='ICO', sizes=[(16,16),(32,32),(48,48)])
    print('Exported five 1200×900 award cards and portrait favicons.')

if __name__ == '__main__':
    main()
